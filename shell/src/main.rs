const ORIGIN: &str = "app://localhost/";
/// How often captured rows are pushed to the UI.
const TICK: Duration = Duration::from_millis(100);

/// `(url path, contents)` of every file trunk built. Generated by build.rs.
static ASSETS: &[(&str, &[u8])] = include!(concat!(env!("OUT_DIR"), "/assets.rs"));

enum UserEvent {
    /// IPC message from the UI.
    Ipc(String),
    /// Result of the launch-time authorization.
    Socket(io::Result<(OwnedFd, Helper)>),
    /// Registration and transfer dates of a domain seen in traffic.
    Domain(DomainInfo),
    /// Reverse DNS name of an address the UI asked about.
    Ptr(PtrInfo),
    /// Outcome of a save, shown briefly in the UI.
    Notice(Notice),
    /// Packet detail the UI asked for.
    Inspect(Box<stream::Inspection>),
    /// Request and response decrypted by the HTTPS proxy.
    Http(Box<Exchange>),
}

/// State of the HTTPS proxy, as the UI shows it.
#[derive(Serialize)]
struct MitmState {
    on: bool,
    /// Port the redirected traffic reaches the proxy on.
    port: u16,
    ca: Option<String>,
    error: Option<String>,
}

#[derive(Serialize)]
struct Notice {
    ok: bool,
    text: String,
}

/// Status shown in the UI. `state` is one of
/// `pending`, `idle`, `capturing`, `stopped` or `error`.
#[derive(Clone, Serialize)]
struct Status {
    state: &'static str,
    text: String,
}

struct App {
    window: tao::window::Window,
    webview: WebView,
    proxy: EventLoopProxy<UserEvent>,
    socket: Option<Arc<OwnedFd>>,
    /// The root helper, kept for HTTPS interception.
    helper: Option<Arc<Helper>>,
    capture: Option<Capture>,
    /// Packets of the latest capture, kept after Stop for "Save pcap".
    recording: Option<Arc<Recording>>,
    names: Names,
    rdap: Rdap,
    ptr: Ptr,
    /// HTTPS proxy, while the user has it on.
    mitm: Option<Mitm>,
    /// Open save dialog. GTK drops a native dialog that nothing holds.
    dialog: Option<gtk::FileChooserNative>,
    status: Status,
}

fn main() -> wry::Result<()> {
    let event_loop = EventLoopBuilder::<UserEvent>::with_user_event().build();
    let window = WindowBuilder::new()
        .with_title("wireshark-rs")
        .with_inner_size(LogicalSize::new(1200.0, 780.0))
        .build(&event_loop)
        .expect("create window");

    // The only privileged step: one prompt at launch, answered on a thread.
    let proxy = event_loop.create_proxy();
    std::thread::spawn(move || {
        // Fails only when the event loop is gone, i.e. during exit.
        let _ = proxy.send_event(UserEvent::Socket(helper::launch()));
    });

    let ifaces = serde_json::to_string(&interfaces()?).expect("string list serializes");
    let proxy = event_loop.create_proxy();
    let webview = WebViewBuilder::new()
        .with_custom_protocol("app".into(), |_, req| asset(req.uri().path()))
        // Keep the webview on the bundled UI: no remote page ever gets the IPC channel.
        .with_navigation_handler(|url| url.starts_with(ORIGIN))
        .with_ipc_handler(move |req| {
            // Fails only when the event loop is gone, i.e. during exit.
            let _ = proxy.send_event(UserEvent::Ipc(req.into_body()));
        })
        .with_initialization_script(format!("window.IFACES = () => {ifaces};"))
        .with_url(ORIGIN)
        .build_gtk(window.default_vbox().expect("tao creates a default vbox"))?;

    let rdap = {
        let proxy = event_loop.create_proxy();
        // Fails only when the event loop is gone, i.e. during exit.
        Rdap::spawn(move |info| drop(proxy.send_event(UserEvent::Domain(info))))
    };
    let ptr = {
        let proxy = event_loop.create_proxy();
        // Fails only when the event loop is gone, i.e. during exit.
        Ptr::spawn(move |info| drop(proxy.send_event(UserEvent::Ptr(info))))
    };
    let mut app = App {
        window,
        webview,
        proxy: event_loop.create_proxy(),
        socket: None,
        helper: None,
        capture: None,
        recording: None,
        names: Names::default(),
        rdap,
        ptr,
        mitm: None,
        dialog: None,
        status: Status {
            state: "pending",
            text: "waiting for capture permission".to_owned(),
        },
    };
    event_loop.run(move |event, _, control_flow| {
        match event {
            Event::NewEvents(StartCause::Init) => *control_flow = ControlFlow::Wait,
            Event::NewEvents(StartCause::ResumeTimeReached { .. }) => app.drain(),
            Event::UserEvent(UserEvent::Ipc(msg)) => app.handle_ipc(&msg),
            Event::UserEvent(UserEvent::Domain(info)) => emit(&app.webview, "domain", &info),
            Event::UserEvent(UserEvent::Ptr(info)) => emit(&app.webview, "ptr", &info),
            Event::UserEvent(UserEvent::Inspect(i)) => emit(&app.webview, "inspect", &i),
            Event::UserEvent(UserEvent::Http(ex)) => emit(&app.webview, "http", &ex),
            Event::UserEvent(UserEvent::Notice(n)) => {
                app.dialog = None;
                emit(&app.webview, "notice", &n);
            }
            Event::UserEvent(UserEvent::Socket(result)) => match result {
                Ok((fd, helper)) => {
                    app.socket = Some(Arc::new(fd));
                    app.helper = Some(Arc::new(helper));
                    app.set_status("idle", "ready".to_owned());
                }
                Err(e) => app.set_status("error", format!("no capture permission: {e}")),
            },
            Event::WindowEvent {
                event: WindowEvent::CloseRequested,
                ..
            } => {
                app.capture = None;
                // tao may exit without dropping the app: delete the pcap
                // and CA files and undo interception now. The explicit
                // `off` waits for the helper; closing the connection would
                // also make it clean up, but without waiting.
                app.recording = None;
                if app.mitm.take().is_some()
                    && let Some(Err(e)) = app.helper.as_ref().map(|h| h.intercept_off())
                {
                    eprintln!("cannot undo interception: {e}");
                }
                app.helper = None;
                *control_flow = ControlFlow::Exit;
                return;
            }
            _ => return,
        }
        *control_flow = if app.capture.is_some() {
            ControlFlow::WaitUntil(Instant::now() + TICK)
        } else {
            ControlFlow::Wait
        };
    })
}

impl App {
    /// IPC messages from the UI: `hello`, `start <interface>`, `stop`,
    /// `save-pcap`, `save <file name>` with the file contents on the
    /// following lines, `ptr <address>...` for reverse DNS names,
    /// `inspect <packet number>`, or `mitm on` / `mitm off`.
    fn handle_ipc(&mut self, msg: &str) {
        if let Some(no) = msg.strip_prefix("inspect ") {
            return self.inspect(no);
        }
        if let Some(on) = msg.strip_prefix("mitm ") {
            return self.set_mitm(on == "on");
        }
        if msg == "hello" {
            // The page may load after the authorization finished: resend the state.
            emit(&self.webview, "status", &self.status);
            return;
        }
        if let Some(addrs) = msg.strip_prefix("ptr ") {
            // Words that are not addresses are ignored.
            addrs
                .split_whitespace()
                .filter_map(|a| a.parse().ok())
                .for_each(|ip| self.ptr.check(ip));
            return;
        }
        if msg == "save-pcap" {
            return self.save_pcap();
        }
        if let Some(rest) = msg.strip_prefix("save ") {
            let (name, body) = rest.split_once('\n').unwrap_or((rest, ""));
            return self.save_text(name, body.to_owned());
        }
        // Dropping a capture stops it and unbinds the socket.
        self.capture = None;
        match msg.split_once(' ') {
            Some(("start", iface))
                if interfaces().is_ok_and(|all| all.iter().any(|i| i == iface)) =>
            {
                let Some(socket) = &self.socket else {
                    return self.set_status(
                        "error",
                        "no capture permission: restart the app to ask again".to_owned(),
                    );
                };
                match Capture::start(Arc::clone(socket), iface) {
                    Ok(c) => {
                        self.recording = Some(Arc::clone(&c.recording));
                        self.capture = Some(c);
                        self.set_status("capturing", format!("capturing on {iface}"));
                    }
                    Err(e) => self.set_status("error", format!("cannot capture on {iface}: {e}")),
                }
            }
            _ if msg == "stop" => self.set_status("stopped", "stopped".to_owned()),
            _ => self.set_status("error", format!("unknown request: {msg}")),
        }
    }

    fn drain(&mut self) {
        let Some(c) = &self.capture else { return };
        let mut rows = Vec::new();
        let mut failed = None;
        for msg in c.rx.try_iter() {
            match msg {
                Ok(mut row) => {
                    for name in self.names.annotate(&mut row) {
                        self.rdap.check(name);
                    }
                    rows.push(row);
                }
                Err(text) => failed = Some(format!("capture on {} failed: {text}", c.iface)),
            }
        }
        if !rows.is_empty() {
            emit(&self.webview, "pkts", &rows);
        }
        if let Some(text) = failed {
            self.capture = None;
            self.set_status("error", text);
        }
    }

    /// Reads the packet and its conversation from the recording on a
    /// thread: a long capture takes a while to scan.
    fn inspect(&self, no: &str) {
        let (Some(rec), Ok(no)) = (self.recording.clone(), no.parse()) else {
            return self.notice(false, "no recorded packet to inspect".to_owned());
        };
        let proxy = self.proxy.clone();
        std::thread::spawn(move || {
            // Fails only when the event loop is gone, i.e. during exit.
            let _ = proxy.send_event(match stream::inspect(&rec, no) {
                Ok(i) => UserEvent::Inspect(Box::new(i)),
                Err(e) => UserEvent::Notice(Notice {
                    ok: false,
                    text: format!("cannot inspect packet {no}: {e}"),
                }),
            });
        });
    }

    fn set_mitm(&mut self, on: bool) {
        let mut state = MitmState {
            on: false,
            port: mitm::PORT,
            ca: None,
            error: None,
        };
        // Undo the redirect before the proxy goes, so no connection is
        // redirected to a closed port. Dropping the proxy deletes its CA file.
        if self.mitm.take().is_some()
            && let Some(Err(e)) = self.helper.as_ref().map(|h| h.intercept_off())
        {
            state.error = Some(format!("cannot undo interception: {e}"));
        }
        if on {
            match self.start_mitm() {
                Ok(m) => {
                    state.on = true;
                    state.ca = Some(m.ca_path.display().to_string());
                    self.mitm = Some(m);
                }
                Err(e) => state.error = Some(format!("cannot intercept HTTPS: {e}")),
            }
        }
        emit(&self.webview, "mitm", &state);
    }

    /// Starts the proxy, then has the helper trust its CA and redirect web
    /// traffic to it. The proxy stops again when the helper fails.
    fn start_mitm(&self) -> io::Result<Mitm> {
        let helper = self
            .helper
            .clone()
            .ok_or_else(|| io::Error::other("no privileged helper: launch was not authorized"))?;
        let marked = Arc::clone(&helper);
        let proxy = self.proxy.clone();
        let m = Mitm::start(
            Arc::new(move |v6| marked.marked_socket(v6)),
            // Fails only when the event loop is gone, i.e. during exit.
            move |ex| drop(proxy.send_event(UserEvent::Http(Box::new(ex)))),
        )?;
        helper.intercept_on(&m.ca_pem)?;
        Ok(m)
    }

    fn set_status(&mut self, state: &'static str, text: String) {
        self.status = Status { state, text };
        emit(&self.webview, "status", &self.status);
    }

    fn save_pcap(&mut self) {
        let Some(rec) = self.recording.clone() else {
            return self.notice(false, "nothing to save: start a capture first".to_owned());
        };
        self.ask_path("Save capture", "capture.pcap", move |path| {
            rec.save_to(path)
                .map(|n| format!("saved {n} bytes to {}", path.display()))
        });
    }

    fn save_text(&mut self, name: &str, body: String) {
        // The UI names the file; keep only a plain file name as the suggestion.
        let name = Path::new(name)
            .file_name()
            .map_or("export.txt".into(), |n| n.to_string_lossy().into_owned());
        self.ask_path("Export packets", &name, move |path| {
            std::fs::write(path, &body).map(|()| format!("saved {}", path.display()))
        });
    }

    /// Asks for a path, runs `save` with it and reports the outcome.
    fn ask_path(
        &mut self,
        title: &str,
        name: &str,
        save: impl FnOnce(&Path) -> io::Result<String> + 'static,
    ) {
        let proxy = self.proxy.clone();
        let dialog = export::ask_path(self.window.gtk_window(), title, name, move |path| {
            let notice = match save(&path) {
                Ok(text) => Notice { ok: true, text },
                Err(e) => Notice {
                    ok: false,
                    text: format!("cannot save {}: {e}", path.display()),
                },
            };
            // Fails only when the event loop is gone, i.e. during exit.
            let _ = proxy.send_event(UserEvent::Notice(notice));
        });
        self.dialog = Some(dialog);
    }

    fn notice(&self, ok: bool, text: String) {
        emit(&self.webview, "notice", &Notice { ok, text });
    }
}

/// Sends `payload` to the UI as a `CustomEvent` whose `detail` is a JSON string.
fn emit<T: serde::Serialize + ?Sized>(webview: &WebView, name: &str, payload: &T) {
    let json = serde_json::to_string(payload).expect("payload serializes");
    let literal = serde_json::to_string(&json).expect("string serializes");
    let script =
        format!("window.dispatchEvent(new CustomEvent({name:?}, {{ detail: {literal} }}));");
    if let Err(e) = webview.evaluate_script(&script) {
        eprintln!("evaluate_script: {e}");
    }
}

fn interfaces() -> io::Result<Vec<String>> {
    let mut names = std::fs::read_dir("/sys/class/net")?
        .map(|entry| Ok(entry?.file_name().to_string_lossy().into_owned()))
        .collect::<io::Result<Vec<_>>>()?;
    names.sort();
    Ok(names)
}

fn asset(path: &str) -> Response<Cow<'static, [u8]>> {
    let path = if path == "/" { "/index.html" } else { path };
    let found = ASSETS.iter().find(|(p, _)| *p == path);
    let mime = match path.rsplit_once('.').map(|(_, ext)| ext) {
        Some("html") => "text/html",
        Some("js") => "text/javascript",
        Some("wasm") => "application/wasm",
        Some("css") => "text/css",
        Some("woff2") => "font/woff2",
        _ => "text/plain",
    };
    let (status, body) = found.map_or((404, &[][..]), |(_, body)| (200, *body));
    Response::builder()
        .status(status)
        .header(CONTENT_TYPE, mime)
        .body(Cow::Borrowed(body))
        .expect("static response is valid")
}
